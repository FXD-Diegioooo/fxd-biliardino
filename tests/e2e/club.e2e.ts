test('salva un singolo, aggiorna punteggio e mostra il dettaglio e la segnalazione', async ({ page }, testInfo) => {
  const pointsBefore = Number(await page.locator('.ranking-row.is-me .rank-value').innerText().then(t => t.replace(/[^0-9]/g,'')));
  const add = testInfo.project.name === 'mobile' ? page.locator('.mobile-nav').getByRole('button', { name: 'Aggiungi', exact: true }) : page.getByRole('button', { name: 'Aggiungi partita', exact: true }).first();
  await add.click();
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('button', { name: '1 contro 1', exact: true }).click();
  const searches = dialog.getByRole('combobox');
  await searches.nth(0).fill('Die');
  await page.getByRole('option', { name: 'Diego Cogliati' }).click();
  await dialog.getByRole('combobox').nth(0).fill('Mar');
  await page.getByRole('option', { name: 'Marco Bianchi' }).click();
  await dialog.getByRole('spinbutton', { name: 'Gol Rossi' }).fill('10');
  await dialog.getByRole('spinbutton', { name: 'Gol Blu' }).fill('7');
  await dialog.getByRole('combobox', { name: 'MVP della partita' }).selectOption('diego');
  await dialog.getByRole('button', { name: 'Aggiungi la partita' }).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.locator('.ranking-row.is-me .rank-value')).toHaveText(`${pointsBefore + 15}pt`);
  await page.locator('.recent-section .match-card').first().click();
  await expect(page.getByRole('heading', { name: 'La partita, nel dettaglio' })).toBeVisible();
  await expect(page.getByText('Vince la squadra rossa')).toBeVisible();
  await expect(page.getByText('Singolo', { exact: true })).toHaveCount(2);
  await page.getByRole('button', { name: 'Segnala partita' }).click();
  await page.getByRole('textbox', { name: 'Cosa non torna?' }).fill('Il risultato non corrisponde.');
  await page.getByRole('button', { name: 'Invia segnalazione' }).click();
  await expect(page.getByText('Segnalazione registrata.', { exact: false })).toBeVisible();
});
test('rifiuta pareggi e giocatori mancanti', async ({ page }, testInfo) => {
  if (testInfo.project.name === 'mobile') await page.locator('.mobile-nav').getByRole('button', { name: 'Aggiungi', exact: true }).click();
  else await page.getByRole('button', { name: 'Aggiungi partita', exact: true }).first().click();
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('spinbutton', { name: 'Gol Blu' }).fill('10');
  await dialog.getByRole('button', { name: 'Aggiungi la partita' }).click();
  await expect(dialog.getByRole('alert')).toContainText('Niente pareggi');
  await expect(page.locator('.match-reaction')).toHaveCount(0);
  await dialog.getByRole('spinbutton', { name: 'Gol Blu' }).fill('8');
  await dialog.getByRole('button', { name: 'Aggiungi la partita' }).click();
  await expect(dialog.getByRole('alert')).toContainText('Ogni giocatore');
});
